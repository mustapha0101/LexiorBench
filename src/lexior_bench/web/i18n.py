def resolve_lang(cookie_value: str | None) -> str:
    return cookie_value if cookie_value in LANGS else DEFAULT_LANG


def translator(lang: str):
    table = STRINGS.get(lang, STRINGS[DEFAULT_LANG])
    fallback = STRINGS[DEFAULT_LANG]

    def t(key: str) -> str:
        return table.get(key) or fallback.get(key) or key

    return t
